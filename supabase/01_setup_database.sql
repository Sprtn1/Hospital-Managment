create view public.patient_history with (security_invoker = true) as
select p.patient_id, p.name as patient_name, m.record_date, d.name as doctor_name,
       m.diagnosis, m.treatment_details, m.medical_notes
from public.patient p
join public.medical_record m on p.patient_id = m.patient_id
join public.doctor d on m.doctor_id = d.doctor_id;

create view public.upcoming_appointments with (security_invoker = true) as
select a.appointment_id, a.appointment_datetime, p.name as patient_name,
       d.name as doctor_name, d.specialization, a.reason_for_visit, a.status
from public.appointment a
join public.patient p on a.patient_id = p.patient_id
join public.doctor d on a.doctor_id = d.doctor_id
where a.status = 'Scheduled';

create view public.bill_balance with (security_invoker = true) as
select b.bill_id, p.name as patient_name, b.total_amount,
       coalesce(sum(pay.amount_paid), 0) as amount_paid,
       b.total_amount - coalesce(sum(pay.amount_paid), 0) as balance,
       b.payment_status
from public.bill b
join public.patient p on b.patient_id = p.patient_id
left join public.payment pay on b.bill_id = pay.bill_id
group by b.bill_id, p.name, b.total_amount, b.payment_status;

create view public.current_admissions with (security_invoker = true) as
select a.admission_id, p.name as patient_name, d.name as doctor_name,
       a.room_number, a.admission_date
from public.admission a
join public.patient p on a.patient_id = p.patient_id
join public.doctor d on a.doctor_id = d.doctor_id
where a.discharge_date is null;

create view public.available_rooms with (security_invoker = true) as
select r.room_number, r.room_type, r.floor, r.capacity,
       count(a.admission_id)::integer as occupied_beds,
       (r.capacity - count(a.admission_id))::integer as beds_available,
       r.availability_status
from public.room r
left join public.admission a
       on a.room_number = r.room_number
      and a.discharge_date is null
where r.availability_status <> 'Maintenance'
group by r.room_number, r.room_type, r.floor, r.capacity, r.availability_status
having count(a.admission_id) < r.capacity;

create view public.low_medication_stock with (security_invoker = true) as
select medication_id, medication_name, quantity_available
from public.medication
where quantity_available < 50;

create view public.doctors_by_department with (security_invoker = true) as
select dep.department_name, d.doctor_id, d.name, d.specialization, d.phone_number
from public.doctor d
join public.department dep on d.department_id = dep.department_id;

create view public.prescription_details with (security_invoker = true) as
select pr.prescription_id, p.name as patient_name, d.name as doctor_name,
       m.medication_name, pi.dosage, pi.frequency, pi.start_date, pi.end_date
from public.prescription pr
join public.patient p on pr.patient_id = p.patient_id
join public.doctor d on pr.doctor_id = d.doctor_id
join public.prescription_item pi on pr.prescription_id = pi.prescription_id
join public.medication m on pi.medication_id = m.medication_id;

