create function private.check_room_available()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
    current_status text;
    room_capacity integer;
    active_admissions integer;
    should_check boolean;
begin
    should_check := new.discharge_date is null;

    if tg_op = 'UPDATE' then
        should_check := should_check and (
            new.room_number is distinct from old.room_number
            or old.discharge_date is not null
        );
    end if;

    if should_check then
        select availability_status, capacity
        into current_status, room_capacity
        from public.room
        where room_number = new.room_number
        for update;

        if current_status = 'Maintenance' then
            raise exception 'The selected room is under maintenance';
        end if;

        select count(*)
        into active_admissions
        from public.admission
        where room_number = new.room_number
          and discharge_date is null
          and admission_id is distinct from new.admission_id;

        if active_admissions >= room_capacity then
            raise exception 'The selected room has no available beds';
        end if;
    end if;

    return new;
end;
$$;

create function private.refresh_room_status(target_room_number text)
returns void
language plpgsql
set search_path = public, pg_temp
as $$
declare
    room_capacity integer;
    current_status text;
    active_admissions integer;
begin
    select capacity, availability_status
    into room_capacity, current_status
    from public.room
    where room_number = target_room_number
    for update;

    if current_status = 'Maintenance' then
        return;
    end if;

    select count(*)
    into active_admissions
    from public.admission
    where room_number = target_room_number
      and discharge_date is null;

    update public.room
    set availability_status = case
        when active_admissions = 0 then 'Available'
        when active_admissions < room_capacity then 'Beds Available'
        else 'Occupied'
    end
    where room_number = target_room_number;
end;
$$;

create function private.refresh_admission_room_status()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    if tg_op = 'DELETE' then
        if old.discharge_date is null then
            perform private.refresh_room_status(old.room_number);
        end if;
        return old;
    end if;

    if tg_op = 'UPDATE' and old.discharge_date is null and (
        new.discharge_date is not null
        or old.room_number is distinct from new.room_number
    ) then
        perform private.refresh_room_status(old.room_number);
    end if;

    if new.discharge_date is null then
        perform private.refresh_room_status(new.room_number);
    end if;

    return new;
end;
$$;

create function private.check_medication_stock()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
    current_quantity integer;
begin
    select quantity_available
    into current_quantity
    from public.medication
    where medication_id = new.medication_id
    for update;

    if current_quantity is null or current_quantity <= 0 then
        raise exception 'Medication is out of stock';
    end if;

    return new;
end;
$$;

create function private.decrease_medication_stock()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    update public.medication
    set quantity_available = quantity_available - 1
    where medication_id = new.medication_id;
    return new;
end;
$$;

create function private.restore_medication_stock()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    update public.medication
    set quantity_available = quantity_available + 1
    where medication_id = old.medication_id;
    return old;
end;
$$;

create function private.change_prescription_medication_stock()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
begin
    update public.medication
    set quantity_available = quantity_available + 1
    where medication_id = old.medication_id;

    update public.medication
    set quantity_available = quantity_available - 1
    where medication_id = new.medication_id;
    return new;
end;
$$;

create function private.refresh_bill_status()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $$
declare
    affected_bill_id bigint;
begin
    if tg_op = 'DELETE' then
        affected_bill_id := old.bill_id;
    else
        affected_bill_id := new.bill_id;
    end if;

    update public.bill b
    set payment_status = case
        when coalesce((select sum(p.amount_paid) from public.payment p where p.bill_id = affected_bill_id), 0) >= b.total_amount then 'Paid'
        when coalesce((select sum(p.amount_paid) from public.payment p where p.bill_id = affected_bill_id), 0) > 0 then 'Partially Paid'
        else 'Unpaid'
    end
    where b.bill_id = affected_bill_id;

    if tg_op = 'UPDATE' and old.bill_id is distinct from new.bill_id then
        update public.bill b
        set payment_status = case
            when coalesce((select sum(p.amount_paid) from public.payment p where p.bill_id = old.bill_id), 0) >= b.total_amount then 'Paid'
            when coalesce((select sum(p.amount_paid) from public.payment p where p.bill_id = old.bill_id), 0) > 0 then 'Partially Paid'
            else 'Unpaid'
        end
        where b.bill_id = old.bill_id;
    end if;

    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end;
$$;

